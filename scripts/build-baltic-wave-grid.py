"""Sea points covering the whole Baltic for the wave-height map (~27 km apart, the spacing of the
Ventspils–Norvik route grid). Land mask: dist/assets/coast.json. Writes worker/baltic-grid.mjs.

Usage: python3 scripts/build-baltic-wave-grid.py
"""
import json, math
from shapely.geometry import shape, Point
from shapely.ops import unary_union
from shapely.prepared import prep

SPACING_KM = 27.0
CLEAR_KM = 5.0          # keep points at least this far from the coastline polygons
land = unary_union([shape(f['geometry']).buffer(0) for f in json.load(open('dist/assets/coast.json'))['features']])
near = prep(land.buffer(CLEAR_KM / 111.0 * 1.6))   # degrees; ×1.6 covers the longitude stretch
inland = prep(land)

def baltic(lat, lon):
    # Baltic Sea with its gulfs and the Danish straits; Kattegat/Skagerrak and the North Sea excluded.
    if lon < 9.8 or lon > 30.4 or lat < 53.8 or lat > 65.95: return False
    if lon < 12.75 and lat > 55.75: return False                    # Kattegat
    if lon < 10.6 and lat > 55.3: return False                     # Little Belt north / Jutland side
    return True

def clear(lat, lon):
    # Distance test in km: check 8 points on a 5 km circle plus the centre.
    k = 111.0; c = math.cos(math.radians(lat))
    for a in range(0, 360, 45):
        dy = CLEAR_KM * math.sin(math.radians(a)) / k; dx = CLEAR_KM * math.cos(math.radians(a)) / (k * c)
        if inland.contains(Point(lon + dx, lat + dy)): return False
    return not inland.contains(Point(lon, lat))

points = []
dlat = SPACING_KM / 111.0
row = 0
lat = 53.85
while lat <= 65.95:
    dlon = SPACING_KM / (111.0 * math.cos(math.radians(lat)))
    lon = 9.8 + (dlon / 2 if row % 2 else 0)      # staggered rows: even spacing on the map
    while lon <= 30.4:
        if baltic(lat, lon) and clear(lat, lon): points.append((round(lat, 3), round(lon, 3)))
        lon += dlon
    lat += dlat * math.sqrt(3) / 2 * 1.1547        # = dlat (kept explicit for readability)
    row += 1

print(len(points), 'points')
body = ',\n'.join('[%s,%s]' % p for p in points)
open('worker/baltic-grid.mjs', 'w').write(
    '// Generated by scripts/build-baltic-wave-grid.py: sea points over the whole Baltic, ~%d km apart.\n'
    'export const BALTIC_GRID = [\n%s\n].map(([lat, lon], i) => ({ id: String(i), lat, lon }));\n' % (SPACING_KM, body))
json.dump(points, open('/tmp/claude-0/-home-claude/64f78ccf-4723-5a98-94cc-3c8228b7c01b/scratchpad/baltic-grid.json', 'w'))
